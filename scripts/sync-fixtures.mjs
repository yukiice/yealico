import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/**
 * 把 docs/rules/samples 的 fixture 同步成可被 Metro 打包的 TS 字符串。
 *
 * 为什么需要：
 * - Node 测试可以直接读 docs，但 Android 上的 Hermes 不能读仓库文件。
 * - 生成文件让 Node 与 Android 使用同一份字节，避免两套 fixture 漂移。
 */

const root = process.cwd();
const base = join(root, 'docs/rules/samples');

const read = path => readFile(join(base, path), 'utf8');

const data = {
  list: {
    html: await read('synthetic-list/page.html'),
    rule: await read('synthetic-list/rule.json'),
    expected: await read('synthetic-list/expected.json'),
  },
  gallery: {
    html: await read('synthetic-gallery/page.html'),
    rule: await read('synthetic-gallery/rule.json'),
    expected: await read('synthetic-gallery/expected.json'),
  },
  json: {
    html: await read('synthetic-json/response.json'),
    rule: await read('synthetic-json/rule.json'),
    expected: await read('synthetic-json/expected.json'),
  },
  unsupported: {
    rule: await read('synthetic-unsupported/rule.json'),
    expected: await read('synthetic-unsupported/expected-plan.json'),
  },
  qr: {
    payload: await read('synthetic-qr/payload.txt'),
  },
};

const output = `// Generated by scripts/sync-fixtures.mjs. Do not edit by hand.
// Source: docs/rules/samples

export const FIXTURE_JSON = ${JSON.stringify(data, null, 2)} as const;
`;

await writeFile(join(root, 'src/engine/fixtures.generated.ts'), output, 'utf8');
console.log('wrote src/engine/fixtures.generated.ts');
