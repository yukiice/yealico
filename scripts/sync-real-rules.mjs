import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/**
 * 把私有仓库里的真实规则同步成可被 Metro 打包的 TS 常量。
 *
 * 只选取阿巴基猫（公开 WordPress 站点）用于网络探针；不把成人站点规则
 * 放进 Android 自检。生成文件仍只在私有仓库/本地测试使用。
 */

const root = process.cwd();
const rulesDir = join(root, 'artifacts', 'yealico-rules');
const files = await readdir(rulesDir);
const abaFile = files.find(
  file => file.startsWith('site-3-') && file.endsWith('.json'),
);
if (!abaFile) {
  throw new Error('site-3 (阿巴基猫) rule fixture not found');
}
const aba = JSON.parse(await readFile(join(rulesDir, abaFile), 'utf8'));
const output = `// Generated by scripts/sync-real-rules.mjs. Do not edit by hand.
// Source: artifacts/yealico-rules/${abaFile}
// Private test fixture; do not redistribute.

export const ABA_RULE_JSON = ${JSON.stringify(aba, null, 2)};
`;

await writeFile(join(root, 'src/engine', 'real-rules.generated.ts'), output, 'utf8');
console.log('wrote src/engine/real-rules.generated.ts');
